"""The menu sources (grub/) as build/build.sh copies them, and dist/ freshness.

menu_files() applies exactly the rules of build.sh's "menu scripts" loop:
  - skipped: any path component starting with '.', editor backups and docs
    (*~ *.swp *.swo *.bak *.orig *.rej #*# *.md), version.cfg and device.cfg
    (generated by the build / written by the installer)
  - errors: symlinks, and i386-pc/*, x86_64-efi/*, fonts/unicode.pf2 (build output)
BB_MENU_DIR overrides the source directory, as it does for build.sh.
"""

from __future__ import annotations

import fnmatch
import hashlib
import json
import os
from dataclasses import dataclass, field
from pathlib import Path

from . import paths
from .msg import Failure

SKIP_PATTERNS = ("*~", "*.swp", "*.swo", "*.bak", "*.orig", "*.rej", "#*#", "*.md")
GENERATED = ("version.cfg", "device.cfg")
INSTALLER_FILES = ("grubenv",)  # /grub/grubenv: created by the installer (layout 2), GRUB writes it
FORBIDDEN = ("i386-pc/*", "x86_64-efi/*", "fonts/unicode.pf2")


def menu_dir(env: dict | None = None) -> Path:
    env = os.environ if env is None else env
    d = env.get("BB_MENU_DIR")
    return Path(d).resolve() if d else paths.GRUB_SRC


def skipped(rel: str) -> bool:
    """True when build.sh would not copy grub/<rel>."""
    if any(part.startswith(".") for part in rel.split("/")):
        return True
    base = rel.rsplit("/", 1)[-1]
    if any(fnmatch.fnmatchcase(base, pat) for pat in SKIP_PATTERNS):
        return True
    return base in GENERATED


def protected(rel: str) -> bool:
    """ESP paths under /grub/ that a menu sync must never write or delete (see
    also manifest_built(): what the build puts there from other sources)."""
    return (rel.rsplit("/", 1)[-1] in GENERATED or rel in INSTALLER_FILES
            or any(fnmatch.fnmatchcase(rel, pat) for pat in FORBIDDEN))


def menu_files(src: Path | None = None) -> dict[str, Path]:
    """{relative path: file} of the menu files build.sh would ship, sorted."""
    src = Path(src) if src else menu_dir()
    if not (src / "grub.cfg").is_file() or not (src / "beast" / "main.cfg").is_file():
        raise Failure(f"menu scripts not found: need {src}/grub.cfg and {src}/beast/main.cfg (BB_MENU_DIR)")
    out: dict[str, Path] = {}
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames.sort()
        d = Path(dirpath)
        # find -type l also lists symlinked directories (os.walk does not descend into them)
        names = sorted(filenames + [n for n in dirnames if (d / n).is_symlink()])
        for name in names:
            p = d / name
            rel = p.relative_to(src).as_posix()
            if skipped(rel):
                continue
            if p.is_symlink():
                raise Failure(f"symlink in menu dir: {p} (copy real files only)")
            if any(fnmatch.fnmatchcase(rel, pat) for pat in FORBIDDEN):
                raise Failure(f"menu dir must not provide {rel} (build output)")
            out[rel] = p
    return dict(sorted(out.items()))


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_manifest(dist: Path | None = None) -> dict | None:
    try:
        return json.loads(((dist or paths.DIST) / "manifest.json").read_text())
    except (OSError, ValueError):
        return None


def manifest_menu(manifest: dict | None) -> dict[str, str]:
    """{grub-relative path: sha256} of the menu files listed in a manifest."""
    out = {}
    for k, v in ((manifest or {}).get("files") or {}).items():
        if k.startswith("esp/grub/") and str(v.get("origin", "")).startswith("repo:grub/"):
            out[k[len("esp/grub/"):]] = v.get("sha256", "")
    return out


def manifest_built(manifest: dict | None) -> set[str]:
    """grub-relative paths the build puts under the ESP's /grub/ from somewhere
    other than grub/ (theme from build/theme, fonts, i386-pc modules). A menu
    sync leaves them alone."""
    return {k[len("esp/grub/"):] for k, v in ((manifest or {}).get("files") or {}).items()
            if k.startswith("esp/grub/") and not str(v.get("origin", "")).startswith("repo:grub/")}


@dataclass
class DistState:
    present: bool
    built_at: float = 0.0
    menu_changed: list[str] = field(default_factory=list)  # grub/ files that differ from dist/
    build_newer: list[str] = field(default_factory=list)  # build/ files newer than dist/

    @property
    def stale(self) -> bool:
        return bool(self.menu_changed or self.build_newer)

    def describe(self) -> str:
        parts = []
        if self.menu_changed:
            parts.append("grub/ changed (" + ", ".join(self.menu_changed[:4])
                         + (", ..." if len(self.menu_changed) > 4 else "") + ")")
        if self.build_newer:
            parts.append("build/ is newer (" + ", ".join(self.build_newer[:4])
                         + (", ..." if len(self.build_newer) > 4 else "") + ")")
        return "; ".join(parts)


def dist_state(dist: Path | None = None) -> DistState:
    """Is dist/ there, and does it match grub/ and build/?

    build.sh sets every file time in dist/ to SOURCE_DATE_EPOCH, so mtimes say
    nothing about when it was built. Menu files are compared by SHA-256 with
    the manifest; build/ sources by mtime against the manifest's ctime (the
    moment the build wrote it).
    """
    dist = dist or paths.DIST
    man_path = dist / "manifest.json"
    manifest = load_manifest(dist)
    if manifest is None:
        return DistState(False)
    st = DistState(True, man_path.stat().st_ctime)
    shipped = manifest_menu(manifest)
    try:
        current = menu_files(paths.GRUB_SRC)
    except Failure:
        current = {}
    for rel, p in current.items():
        if shipped.get(rel) != sha256(p.read_bytes()):
            st.menu_changed.append(f"grub/{rel}")
    for rel in shipped:
        if rel not in current:
            st.menu_changed.append(f"grub/{rel} (removed)")
    build_dir = paths.REPO / "build"
    if build_dir.is_dir():
        for dirpath, dirnames, filenames in os.walk(build_dir):
            dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d != "__pycache__")
            for f in sorted(filenames):
                if f.startswith(".") or skipped(f):
                    continue
                p = Path(dirpath) / f
                if p.stat().st_mtime > st.built_at:
                    st.build_newer.append(p.relative_to(paths.REPO).as_posix())
    return st
