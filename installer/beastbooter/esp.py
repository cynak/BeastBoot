"""The ESP (partition 2): device.cfg, the marker file, the files that go on it.

The ESP itself is a FAT32 volume (layout 2) written by fatfs.build_esp and
read with fatfs.FatVolume (no mtools). Besides the dist's esp/ tree it holds
the installer's device.cfg, the marker and grub/grubenv; `update` carries
grubenv and the installed firmware packs (beast-net/firmware/) over.
"""

from __future__ import annotations

import json
import os
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from .cpio import FIRMWARE_ROOT, HEADER_SIZE, TRAILER, archive_names
from .errors import BeastError
from .layout import (
    DEVICE_CFG_PATH,
    ESP_MARKER_PATH,
    FILESYSTEMS,
    FIRMWARE_DIR,
    GRUBENV_PATH,
    GRUBENV_SIZE,
    LAYOUT_VERSION,
    LAYOUTS,
)

MARKER_MAGIC = "beast-booter"

# --------------------------------------------------------------------------
# GRUB `set` lines
# --------------------------------------------------------------------------

_SET_RE = re.compile(r'^\s*set\s+([A-Za-z_][A-Za-z0-9_]*)=(?:"((?:[^"\\]|\\.)*)"|(\S*))\s*(?:#.*)?$')


def grub_quote(value: str) -> str:
    """Double-quoted GRUB script string."""
    if "\n" in value or "\r" in value:
        raise BeastError("value for device.cfg must not contain newlines")
    return '"' + re.sub(r'([\\"$])', r"\\\1", value) + '"'


def parse_set_lines(text: str) -> dict[str, str]:
    """Parse `set name="value"` / `set name=value` lines (other lines are ignored)."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        m = _SET_RE.match(line)
        if m:
            quoted, bare = m.group(2), m.group(3)
            out[m.group(1)] = re.sub(r"\\(.)", r"\1", quoted) if quoted is not None else bare
    return out


@dataclass
class DeviceConfig:
    install_id: str
    layout: str
    data_fs: str
    data_uuid: str  # as GRUB prints it
    data_uuid_linux: str  # blkid form
    data_label: str
    serial: bool = False

    KEYS = (
        ("bb_install_id", "install_id"),
        ("bb_layout", "layout"),
        ("bb_data_fs", "data_fs"),
        ("bb_data_uuid", "data_uuid"),
        ("bb_data_uuid_linux", "data_uuid_linux"),
        ("bb_data_label", "data_label"),
    )

    def render(self) -> str:
        lines = [f"set {k}={grub_quote(getattr(self, attr))}" for k, attr in self.KEYS]
        lines.append(f"set bb_serial={grub_quote('1' if self.serial else '0')}")
        return "\n".join(lines) + "\n"

    @classmethod
    def parse(cls, text: str) -> DeviceConfig:
        vals = parse_set_lines(text)
        missing = [k for k, _ in cls.KEYS if k != "bb_data_label" and not vals.get(k)]
        if missing:
            raise BeastError(f"device.cfg is incomplete (missing {', '.join(missing)})")
        cfg = cls(**{attr: vals.get(k, "") for k, attr in cls.KEYS}, serial=vals.get("bb_serial", "0") == "1")
        if cfg.layout not in LAYOUTS:
            raise BeastError(f"device.cfg: unknown layout {cfg.layout!r}")
        if cfg.data_fs not in FILESYSTEMS:
            raise BeastError(f"device.cfg: unknown filesystem {cfg.data_fs!r}")
        return cfg


def render_marker(install_id: str, version: str) -> str:
    """BEAST-BOOTER.ID: identifies a beast-booter ESP (key=value lines)."""
    return (
        f"{MARKER_MAGIC}\n"
        f"install_id={install_id}\n"
        f"layout_version={LAYOUT_VERSION}\n"
        f"version={version}\n"
    )


def parse_marker(text: str) -> dict[str, str] | None:
    """Parsed marker, or None if the text is not a beast-booter marker."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != MARKER_MAGIC:
        return None
    out = {}
    for line in lines[1:]:
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def marker_layout_version(marker: dict[str, str]) -> int | None:
    """layout_version from a parsed marker (markers without one are layout 1);
    None if it is not a number."""
    value = marker.get("layout_version", "1").strip()
    return int(value) if value.isdigit() else None


# --------------------------------------------------------------------------
# grub/grubenv
# --------------------------------------------------------------------------

GRUBENV_SIGNATURE = b"# GRUB Environment Block\n"
# What grub-editenv (GRUB 2.12+) writes after the signature.
GRUBENV_MESSAGE = b"# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"


def new_grubenv() -> bytes:
    """An empty GRUB environment block, byte for byte what `grub-editenv FILE create` writes."""
    head = GRUBENV_SIGNATURE + GRUBENV_MESSAGE
    return head + b"#" * (GRUBENV_SIZE - len(head))


def is_grubenv(data: bytes) -> bool:
    """A block GRUB's load_env/save_env accept: 1024 bytes starting with the signature."""
    return len(data) == GRUBENV_SIZE and data.startswith(GRUBENV_SIGNATURE)


# --------------------------------------------------------------------------
# ESP contents
# --------------------------------------------------------------------------


def is_kept_path(path: str) -> bool:
    """ESP paths `update` carries over from the old ESP: grub/grubenv and the
    installed firmware packs (beast-net/firmware/**)."""
    p = path.strip("/").lower()
    return p == GRUBENV_PATH.lower() or p.startswith(FIRMWARE_DIR.lower() + "/")


def esp_files(esp_dir: str | os.PathLike, device_cfg: DeviceConfig, marker: str,
              keep: dict[str, bytes] | None = None) -> dict[str, bytes]:
    """{ESP path: contents}: every file of the (verified, staged) dist esp/ tree,
    plus the installer's device.cfg and marker, a new grub/grubenv, and `keep`
    (files carried over by update: grub/grubenv, beast-net/firmware/**), which
    win over the dist's files of the same name."""
    root = Path(esp_dir)
    files: dict[str, bytes] = {}
    for dirpath, dirs, names in os.walk(root):
        dirs.sort()
        for name in sorted(names):
            full = Path(dirpath) / name
            files[full.relative_to(root).as_posix()] = full.read_bytes()
    files[DEVICE_CFG_PATH] = device_cfg.render().encode("utf-8")
    files[ESP_MARKER_PATH] = marker.encode("utf-8")
    files[GRUBENV_PATH] = new_grubenv()
    if keep:
        lower = {k.lower(): k for k in files}
        for path, data in keep.items():
            files.pop(lower.get(path.lower(), path), None)
            files[path] = data
    return files


def read_kept_files(vol, rep=None) -> dict[str, bytes]:
    """The files `update` carries over from an ESP (FatVolume): a valid
    grub/grubenv (an invalid one is replaced by a new, empty block, with a
    warning) and everything under beast-net/firmware/."""
    keep: dict[str, bytes] = {}
    if vol.exists(GRUBENV_PATH):
        data = vol.read_file(GRUBENV_PATH)
        if is_grubenv(data):
            keep[GRUBENV_PATH] = data
        elif rep is not None:
            rep.warn(f"{GRUBENV_PATH} on the drive is not a GRUB environment block; it is replaced by an empty one")
    todo = [FIRMWARE_DIR] if vol.exists(FIRMWARE_DIR) else []
    while todo:
        d = todo.pop()
        for e in vol.listdir(d):
            path = f"{d}/{e.name}"
            if e.is_dir:
                todo.append(path)
            else:
                keep[path] = vol.read_file(path)
    return keep


def read_esp_text(vol, path: str) -> str | None:
    """Text of a file on a FatVolume, or None if it does not exist (or is unreadable)."""
    try:
        if not vol.exists(path):
            return None
        return vol.read_file(path).decode("utf-8", errors="replace")
    except BeastError:
        return None


# --------------------------------------------------------------------------
# Room for firmware packs on the ESP (docs/BEASTNET.md section 6)
#
# One formula for every check: `firmware install`'s final one (exact sizes),
# `firmware fetch --for-image/--for-device` and the GUI before anything is
# downloaded (sizes from the catalog, which fetch's archives match exactly).
# --------------------------------------------------------------------------

INSTALLED_JSON = "installed.json"  # in FIRMWARE_DIR, next to the packs


def _cpio_header(name: str) -> int:
    n = HEADER_SIZE + len(name.encode("utf-8")) + 1
    return n + (-n % 4)


def fw_archive_size(files: Iterable[tuple[str, int]]) -> int:
    """Exact size of the <id>.cpio `firmware fetch` builds (cpio.iter_pack) from
    [(firmware path, file size)], e.g. a catalog pack's files."""
    sizes = dict(files)
    total = _cpio_header(TRAILER)
    for name, is_dir in archive_names(sizes):
        total += _cpio_header(name)
        if not is_dir:
            n = sizes[name[len(FIRMWARE_ROOT) + 1:]]
            total += n + (-n % 4)
    return total


def installed_entry_estimate(paths: Iterable[str]) -> int:
    """Generous size of a pack's entry in installed.json (indented JSON: id, tag,
    kernel, cpio_sha256 and path / sha256 / size per file)."""
    return 400 + sum(134 + len(json.dumps(p)) for p in paths)


@dataclass(frozen=True)
class FwSpace:
    need: int  # what the packs and the new installed.json take, in whole clusters
    free: int  # free on the ESP now
    reclaimed: int  # freed by what they replace: the same packs installed before, the old installed.json
    label: str = ""  # the ESP's volume label, for messages

    @property
    def available(self) -> int:
        return self.free + self.reclaimed

    @property
    def fits(self) -> bool:
        return self.need <= self.available


def fw_space(new: Mapping[str, int], *, free: int, cluster: int, on_drive: Mapping[str, int],
             json_size: int, label: str = "") -> FwSpace:
    """Room check for installing packs {id: .cpio size} on an ESP with `free` bytes and
    `cluster`-byte clusters. `on_drive` maps the names in beast-net/firmware/ (any case)
    to their sizes: a pack being re-installed and installed.json are replaced, so their
    clusters count as available. `json_size` is the new installed.json's size."""
    cs = max(1, cluster)

    def clusters(n: int) -> int:
        return -(-n // cs) * cs

    have = {k.lower(): v for k, v in on_drive.items()}
    need = sum(clusters(n) for n in new.values()) + clusters(json_size) + 2 * cs  # + new directories
    reclaimed = sum(clusters(have.get(f"{pid}.cpio", 0)) for pid in new) + clusters(have.get(INSTALLED_JSON, 0))
    return FwSpace(need, free, reclaimed, label)

