#!/usr/bin/env bash
# Fetch the build/test/debug toolchain into .tools/ WITHOUT root.
#
# On Debian/Ubuntu you can instead install the same packages system-wide:
#   sudo apt install grub-efi-amd64-signed \
#        sbsigntool mtools dosfstools exfatprogs ntfs-3g xorriso squashfs-tools socat \
#        qemu-system-x86 qemu-system-gui ovmf python3-pytest python3-virt-firmware gdb
#
# GRUB itself (the modules, kernel.img, boot images and grub-mkimage dist/ is
# built from, with their debug symbols) is built from pinned source by
# build/grub/grubsrc.py; this script runs it once (BB_SKIP_GRUB_BUILD=1 skips
# it, `make build` does it anyway). It needs gcc, make, autoconf, automake,
# python3, pkg-config and libfreetype-dev on the host; bison, flex, autopoint
# and gawk it unpacks itself when missing. Ubuntu's grub-efi-amd64-signed is
# still fetched: only the e2e stub images use it (its SBAT).
# shim and MokManager are always Debian's (build/shim/debian-shim.lock), fetched
# by step 3b below into .tools/debian whatever the host has installed.
#
# How it works: packages missing on the host (and the dependencies apt says
# they need, from a rootless `apt-get install -s` simulation) are downloaded
# with `apt-get download` (no root; apt verifies them against the signed
# archive index), unpacked under .tools/root with `dpkg-deb -x`, and get small
# wrappers in .tools/bin that set LD_LIBRARY_PATH / PYTHONPATH (and, for QEMU,
# QEMU_MODULE_DIR) only for those tools.
#
# Version-locked extras:
#   - QEMU UI modules (qemu-system-gui: GTK/SDL, qemu-system-modules-opengl)
#     must be the same build as the qemu-system-x86 binary that runs; when that
#     binary comes from .tools they are fetched at exactly its version.
#   - GRUB debug symbols must be the same build as the GRUB modules in
#     BB_GRUB_BIOS_DIR / BB_GRUB_EFI_DIR. The source build has them next to the
#     modules (kernel.exec, *.module). Only for module directories from Ubuntu
#     packages (grub-pc-bin, grub-efi-amd64-bin, chosen by the user) are
#     grub-pc-dbg / grub-efi-amd64-dbg fetched at exactly the module package's
#     version into .tools/debs-dbg, unpacked into .tools/grub-dbg (not
#     .tools/root, so build provenance is unaffected), and their code is
#     compared with the modules (devtools/gdb/grubsyms.py verify). If the
#     matching version cannot be fetched, or the code differs, this script
#     says so loudly and exits 3 after everything else is done (the build/test
#     toolchain is then complete; only `bb-dev gdb` is affected).
#     BB_SKIP_GRUB_DBG=1 skips them.
#
# Exit status: 0 ok, 3 only GRUB debug symbols failed, other = toolchain failed.
#
# Idempotent: a second run downloads nothing, unpacks only new .deb files and
# rewrites only the wrappers it owns (files in .tools/bin that it did not
# write, e.g. other tools' binaries, are never touched or deleted).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS="$ROOT/.tools"
DEBS="$TOOLS/debs"
DBG_DEBS="$TOOLS/debs-dbg"
SYSROOT="$TOOLS/root"
DBGROOT="$TOOLS/grub-dbg"
STAMPS="$SYSROOT/.bb-unpacked"
WRAPPER_MARK="# generated by scripts/bootstrap-tools.sh"
mkdir -p "$DEBS" "$SYSROOT" "$TOOLS/bin" "$STAMPS"

log()  { echo "bootstrap: $*"; }
warn() { echo "bootstrap: WARNING: $*" >&2; }
FAILURES=()
fail_later() { echo "bootstrap: ERROR: $*" >&2; FAILURES+=("$1"); }

for t in apt-get apt-cache dpkg dpkg-deb dpkg-query python3; do
  command -v "$t" >/dev/null || { echo "bootstrap: error: $t not found (this script needs a Debian/Ubuntu host)" >&2; exit 1; }
done

PKGS=(
  # boot chain (build/build.sh; GRUB is built from source, the signed GRUB is for the e2e stubs)
  grub-efi-amd64-signed sbsigntool
  # images, filesystems, ISOs
  mtools dosfstools exfatprogs ntfs-3g libntfs-3g89t64
  xorriso libisoburn1t64 libisofs6t64 libburn4t64
  squashfs-tools
  # QEMU + firmware
  ovmf-generic seabios ipxe-qemu qemu-system-x86 qemu-system-common qemu-system-data
  libfdt1 libpmem1 libndctl6 libdaxctl1 librdmacm1t64 libslirp0 libcacard0
  libmpathpersist0 libusbredirparser1t64 libaio1t64
  # test + dev tools
  python3-virt-firmware python3-pefile python3-pytest python3-pluggy python3-iniconfig
  socat
)

installed() { dpkg-query -W -f='${Status}' "$1" 2>/dev/null | grep -q 'ok installed'; }
deb_ver()   { dpkg-deb -f "$1" Version; }
# have_deb DIR PKG VERSION: is PKG_VERSION_*.deb already downloaded? (':' is '%3a' in file names)
have_deb()  { compgen -G "$1/${2}_${3//:/%3a}_*.deb" >/dev/null; }
tools_deb() { compgen -G "$DEBS/${1}_*.deb" | head -n1 || true; }   # first downloaded .deb of PKG
# apt_inst PKG...: "pkg=version" for everything a rootless `apt-get install -s`
# would install on this host (the packages plus their missing dependencies).
# "Inst pkg [current] (new ...)" for upgrades, "Inst pkg (new ...)" otherwise.
apt_inst() {
  apt-get install -s --no-install-recommends "$@" 2>/dev/null \
    | awk '/^Inst /{ for (i = 3; i <= NF; i++) if ($i ~ /^\(/) { print $2 "=" substr($i, 2); break } }'
}

# download DIR PKG=VERSION... : apt-get download what is not there yet.
download() {
  local dir="$1"; shift
  local want=() spec
  for spec in "$@"; do
    have_deb "$dir" "${spec%%=*}" "${spec#*=}" || want+=("$spec")
  done
  [ "${#want[@]}" -gt 0 ] || return 0
  log "downloading ${#want[@]} package(s) into ${dir#"$ROOT"/}: ${want[*]}"
  (cd "$dir" && apt-get download "${want[@]}")
}

# ---------------------------------------------------------------------------
# 1. Packages missing on the host, plus the dependencies apt says they need
# ---------------------------------------------------------------------------
NEED=()
for p in "${PKGS[@]}"; do
  installed "$p" || NEED+=("$p")
done

# Nothing to resolve when every missing package was downloaded on an earlier run.
NEW=()
for p in "${NEED[@]}"; do
  [ -n "$(tools_deb "$p")" ] || NEW+=("$p")
done

if [ "${#NEW[@]}" -gt 0 ]; then
  SPECS=()
  if out="$(apt_inst "${NEED[@]}")"; then
    while read -r spec; do [ -n "$spec" ] && SPECS+=("$spec"); done <<<"$out"
  fi
  [ "${#SPECS[@]}" -gt 0 ] || warn "apt could not resolve dependencies for: ${NEED[*]}; fetching just those"
  if [ "${#SPECS[@]}" -eq 0 ]; then
    for p in "${NEED[@]}"; do
      deb="$(tools_deb "$p")"
      if [ -n "$deb" ]; then SPECS+=("$p=$(deb_ver "$deb")"); else SPECS+=("$p=$(apt-cache policy "$p" | awk '/Candidate:/ {print $2}')"); fi
    done
  fi
  # Keep packages we already have at whatever version we have them.
  KEEP=()
  for spec in "${SPECS[@]}"; do
    p="${spec%%=*}"
    if deb="$(tools_deb "$p")" && [ -n "$deb" ]; then continue; fi
    KEEP+=("$spec")
  done
  [ "${#KEEP[@]}" -eq 0 ] || download "$DEBS" "${KEEP[@]}"
fi

# ---------------------------------------------------------------------------
# 2. QEMU UI modules at exactly the version of the QEMU binary in .tools
# ---------------------------------------------------------------------------
if qdeb="$(tools_deb qemu-system-x86)" && [ -n "$qdeb" ]; then
  QVER="$(deb_ver "$qdeb")"
  download "$DEBS" "qemu-system-gui=$QVER" "qemu-system-modules-opengl=$QVER"
  # Libraries the GUI modules need that the host lacks (normally none on a desktop);
  # resolved once per QEMU version.
  LIBS=()
  gui_stamp="$DEBS/.gui-deps-${QVER//:/%3a}.done"
  resolved=0
  if [ ! -f "$gui_stamp" ] && out="$(apt_inst "qemu-system-gui=$QVER" "qemu-system-modules-opengl=$QVER")"; then
    resolved=1
    while read -r spec; do
      pkg="${spec%%=*}"
      case "$pkg" in ""|qemu-*|ubuntu-virt*|ubuntu-helper-virt*) continue ;; esac
      [ -n "$(tools_deb "$pkg")" ] && continue
      LIBS+=("$spec")
    done <<<"$out"
  fi
  [ "${#LIBS[@]}" -eq 0 ] || download "$DEBS" "${LIBS[@]}"
  [ "$resolved" = 0 ] || touch "$gui_stamp"
fi

# ---------------------------------------------------------------------------
# 3. Unpack (each .deb once; a newer download of a package is unpacked again)
# ---------------------------------------------------------------------------
# unpacked DEB: are all of its regular files already in the sysroot, same size?
# (Avoids rewriting binaries other jobs may be running from.)
unpacked() {
  local listing perms _owner size _date _time path
  # The whole listing first: returning early from a loop reading dpkg-deb's
  # pipe would kill its tar with SIGPIPE ("tar subprocess was killed").
  listing="$(dpkg-deb -c "$1")" || return 1
  while read -r perms _owner size _date _time path; do
    case "$perms" in -*) ;; *) continue ;; esac
    path="${path#./}"
    [ "$(stat -c %s "$SYSROOT/$path" 2>/dev/null)" = "$size" ] || return 1
  done <<<"$listing"
}
n=0
for d in "$DEBS"/*.deb; do
  [ -e "$d" ] || continue
  stamp="$STAMPS/$(basename "$d").done"
  [ "$stamp" -nt "$d" ] && continue
  if ! unpacked "$d"; then
    dpkg-deb -x "$d" "$SYSROOT"
    n=$((n + 1))
  fi
  touch "$stamp"
done
[ "$n" -eq 0 ] || log "unpacked $n package(s) into ${SYSROOT#"$ROOT"/}"

# ---------------------------------------------------------------------------
# 3b. Debian's shim + MokManager (build/shim/debian-shim.lock): downloaded from
# deb.debian.org (snapshot.debian.org fallback), checked against the pinned
# SHA-256, unpacked into .tools/debian/root (BB_DEBIAN_DIR, BB_SHIM_DIR).
# ---------------------------------------------------------------------------
python3 -I "$ROOT/build/shim/fetch.py" fetch "$TOOLS/debian"

# ---------------------------------------------------------------------------
# 4. Wrappers in .tools/bin (only ones this script owns)
# ---------------------------------------------------------------------------
LIBDIR="$SYSROOT/usr/lib/x86_64-linux-gnu"
PYDIR="$SYSROOT/usr/lib/python3/dist-packages"
QMODDIR="$LIBDIR/qemu"
ours() {  # is .tools/bin/NAME absent, or a wrapper written by this script (any version)?
  [ ! -e "$1" ] && return 0
  [ -f "$1" ] && [ "$(stat -c %s "$1")" -lt 4096 ] || return 1
  grep -qF "$WRAPPER_MARK" "$1" && return 0
  # wrappers from before the marker existed: exec into our sysroot
  grep -qF "exec \"$SYSROOT/" "$1"
}
written=0
for dir in "$SYSROOT/usr/bin" "$SYSROOT/usr/sbin"; do
  [ -d "$dir" ] || continue
  for tool in "$dir"/*; do
    [ -f "$tool" ] && [ -x "$tool" ] || continue
    name="$(basename "$tool")"
    out="$TOOLS/bin/$name"
    if ! ours "$out"; then
      warn "not replacing .tools/bin/$name (not a bootstrap wrapper)"
      continue
    fi
    extra=""
    case "$name" in
      qemu-*) [ -d "$QMODDIR" ] && extra="QEMU_MODULE_DIR=\"\${QEMU_MODULE_DIR:-$QMODDIR}\" \\" ;;
    esac
    new="$(cat <<EOF
#!/bin/sh
$WRAPPER_MARK
LD_LIBRARY_PATH="$LIBDIR\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}" \\
PYTHONPATH="$PYDIR\${PYTHONPATH:+:\$PYTHONPATH}" \\
${extra:+$extra
}exec "$tool" "\$@"
EOF
)"
    if [ ! -e "$out" ] || [ "$(cat "$out")" != "$new" ]; then
      printf '%s\n' "$new" > "$out.tmp.$$"
      chmod +x "$out.tmp.$$"
      mv -f "$out.tmp.$$" "$out"   # atomic: a tool starting right now sees old or new, never half
      written=$((written + 1))
    fi
  done
done
[ "$written" -eq 0 ] || log "wrote $written wrapper(s) in .tools/bin"

# ---------------------------------------------------------------------------
# 5. GRUB debug symbols, locked to the modules in BB_GRUB_*_DIR (helpers; run below)
# ---------------------------------------------------------------------------
# module_pkg_version DIR PKG: version of PKG that provides DIR (host or .tools)
module_pkg_version() {
  local dir="$1" pkg="$2" deb
  case "$dir" in
    "$SYSROOT"/*)
      deb="$(tools_deb "$pkg")"
      [ -n "$deb" ] && deb_ver "$deb" ;;
    *)
      dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null ;;
  esac
}

grub_dbg() {  # <platform dir name> <module dir> <module pkg> <dbg pkg> <variable naming the module dir>
  local plat="$1" moddir="$2" binpkg="$3" dbgpkg="$4" var="$5" ver deb dest where=""
  if [ ! -f "$moddir/kernel.img" ]; then
    if installed "$binpkg"; then where="installed on the host"
    elif [ -n "$(tools_deb "$binpkg")" ]; then where="unpacked into ${SYSROOT#"$ROOT"/}"
    fi
    if [ -n "$where" ]; then
      # The package is there, so this is a wrong module directory, not a
      # missing package: say so (exit 3) rather than skip quietly.
      fail_later "$dbgpkg: $var=$moddir has no GRUB modules (kernel.img), although $binpkg is $where.
       Unset $var (scripts/dev-env.sh then finds the modules) or point it at the $binpkg module directory, then: make tools"
    else
      warn "$binpkg modules not found in $moddir; skipping $dbgpkg"
    fi
    return 0
  fi
  if [ -f "$moddir/kernel.exec" ]; then
    log "GRUB $plat debug symbols: next to the modules ($moddir)"
    return 0
  fi
  ver="$(module_pkg_version "$moddir" "$binpkg")"
  if [ -z "$ver" ]; then
    fail_later "$dbgpkg: cannot tell which $binpkg version provides $moddir"
    return 0
  fi
  mkdir -p "$DBG_DEBS"
  if ! download "$DBG_DEBS" "$dbgpkg=$ver"; then
    fail_later "$dbgpkg $ver (matching $binpkg $ver, the modules dist/ is built from) is not available from apt.
       apt-cache policy $dbgpkg shows what the archive has. Either bring the modules to that version
       (system: sudo apt install $binpkg $dbgpkg; .tools: remove .tools/debs/${binpkg}_*.deb, then make tools && make build)
       or install $dbgpkg=$ver from a snapshot of the archive."
    return 0
  fi
  deb="$(compgen -G "$DBG_DEBS/${dbgpkg}_${ver//:/%3a}_*.deb" | head -n1)"
  local got_pkg got_ver
  got_pkg="$(dpkg-deb -f "$deb" Package)"; got_ver="$(dpkg-deb -f "$deb" Version)"
  if [ "$got_pkg" != "$dbgpkg" ] || [ "$got_ver" != "$ver" ]; then
    fail_later "$deb is $got_pkg $got_ver, expected $dbgpkg $ver"
    return 0
  fi
  dest="$DBGROOT/usr/lib/grub/$plat"
  stamp="$DBGROOT/.$plat.$(basename "$deb").done"
  dbg_extract() {
    rm -rf "$dest" "$DBGROOT"/."$plat".*.done
    mkdir -p "$DBGROOT"
    dpkg-deb -x "$deb" "$DBGROOT"
    touch "$stamp"
    log "unpacked $dbgpkg $ver into ${dest#"$ROOT"/}"
  }
  dbg_verify() { python3 -I "$ROOT/devtools/gdb/grubsyms.py" verify "$dest" "$moddir" --all --quiet; }
  local fresh=0 matched=0 vout
  if [ ! -f "$stamp" ] || [ "$deb" -nt "$stamp" ] || [ ! -f "$dest/kernel.exec" ]; then
    dbg_extract
    fresh=1
  fi
  if vout="$(dbg_verify 2>&1)"; then
    matched=1
  elif [ "$fresh" = 0 ]; then
    # An earlier unpack that was changed or damaged since: unpack the cached
    # .deb once more before calling it a mismatch.
    log "$dbgpkg: ${dest#"$ROOT"/} does not match $moddir; unpacking ${deb#"$ROOT"/} again"
    dbg_extract
    vout="$(dbg_verify 2>&1)" && matched=1
  fi
  if [ "$matched" = 1 ]; then
    log "$dbgpkg $ver: kernel.exec and all $(compgen -G "$dest/*.module" | wc -l) .module files match $moddir"
  else
    [ -z "$vout" ] || printf '%s\n' "$vout" >&2
    fail_later "$dbgpkg $ver (freshly unpacked from ${deb#"$ROOT"/}) does NOT match the modules in $moddir
       (see MISMATCH lines above): they are different builds, and gdb would show wrong symbols.
       Bring both to one version (make tools && make build), or remove ${DBG_DEBS#"$ROOT"/}/${dbgpkg}_*.deb to fetch it again."
  fi
}

# ---------------------------------------------------------------------------
# 5a. GRUB from source: the modules dist/ ships (scripts/dev-env.sh then points
#     BB_GRUB_EFI_DIR / BB_GRUB_BIOS_DIR at them, debug symbols included)
# ---------------------------------------------------------------------------
if [ "${BB_SKIP_GRUB_BUILD:-0}" != 1 ] && [ -f "$ROOT/build/grub/grubsrc.py" ]; then
  log "GRUB from source (build/grub/grubsrc.py; a few minutes the first time, then cached)"
  if gout="$(python3 -I "$ROOT/build/grub/grubsrc.py" build --quiet)"; then
    log "GRUB: ${gout##*$'\n'}"
  else
    warn "GRUB source build failed (see above; logs in .tools/cache/grub-src/work/). make build retries it."
  fi
fi

if [ "${BB_SKIP_GRUB_DBG:-0}" = 1 ]; then
  log "BB_SKIP_GRUB_DBG=1: skipping GRUB debug symbols"
else
  # The module directories the build uses (system preferred, .tools fallback),
  # resolved now that .tools/root is unpacked: dev-env.sh keeps a directory the
  # caller chose, but picks again one it had chosen itself as a fallback
  # before .tools/root existed (e.g. in an environment from an earlier source).
  # shellcheck source=/dev/null
  source "$ROOT/scripts/dev-env.sh"
  grub_dbg i386-pc "$BB_GRUB_BIOS_DIR" grub-pc-bin grub-pc-dbg BB_GRUB_BIOS_DIR
  grub_dbg x86_64-efi "$BB_GRUB_EFI_DIR" grub-efi-amd64-bin grub-efi-amd64-dbg BB_GRUB_EFI_DIR
fi

# ---------------------------------------------------------------------------
# 6. Report
# ---------------------------------------------------------------------------
QEMU_BIN="$TOOLS/bin/qemu-system-x86_64"
[ -x "$QEMU_BIN" ] || QEMU_BIN="$(command -v qemu-system-x86_64 || true)"
if [ -n "$QEMU_BIN" ]; then
  if "$QEMU_BIN" -display help 2>/dev/null | grep -qx gtk; then
    log "QEMU GTK display: available"
  else
    warn "QEMU cannot load its GTK display module (bb-dev vm falls back to VNC/serial)"
  fi
fi
command -v gdb >/dev/null || warn "gdb is not installed (needed only for bb-dev gdb): sudo apt install gdb"

if [ "${#FAILURES[@]}" -gt 0 ]; then
  echo "bootstrap: FAILED: ${#FAILURES[@]} GRUB debug-symbol problem(s) above; the build/test toolchain is ready." >&2
  exit 3
fi
log "done. Use 'source scripts/dev-env.sh' or run targets via make."
