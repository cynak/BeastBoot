#!/usr/bin/env python3
"""ISO x data-filesystem compatibility table, from the real-ISO boot results.

Reads the catalog (tests/e2e/real_isos.json) and the latest results of the
current BeastBoot version (out/real/results.jsonl, see tests/e2e/REAL_ISOS.md)
and writes a Markdown table. A cell says "boots" only when that ISO passed on
every firmware mode listed for it, on that filesystem, in this version's run.

  scripts/iso_matrix.py              print the table
  scripts/iso_matrix.py --readme     replace the table between the markers in README.md
  scripts/iso_matrix.py --check      exit 1 if README.md's table is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests" / "e2e"))

from bbe2e import realiso  # noqa: E402

FILESYSTEMS = [("exfat", "exFAT"), ("fat32", "FAT32"), ("ntfs", "NTFS")]
MODES = {"uefi": "UEFI", "bios": "BIOS"}
START, END = "<!-- iso-matrix:start -->", "<!-- iso-matrix:end -->"
# Recipes whose ISO cannot read NTFS: the menu refuses them on NTFS with
# ntfs-unsupported (grub/beast/lib.cfg; tests/e2e/test_e2e_recipes.py).
NTFS_REFUSED = {"dracut-live", "anaconda"}

LEGEND = (
    "✅ boots on UEFI and BIOS (Secure Boot off), tested with the real ISO · "
    "🚫 refused with an explanation: the ISO's own start-up code cannot read NTFS · "
    "📏 does not fit: FAT32 files are limited to 4 GiB · "
    "– not tested yet"
)


def cell(entry: dict, fs: str, rows: dict) -> str:
    if fs == "fat32" and entry.get("size", 0) > realiso.FAT32_MAX_FILE:
        return "📏"
    if fs == "ntfs" and entry.get("recipe") in NTFS_REFUSED:
        return "🚫"
    modes = [m for m in entry["modes"] if m in MODES]
    got = [rows.get((entry["id"], m, fs)) for m in modes]
    if not modes or any(r is None for r in got):
        return "–"
    if all(r["status"] == "pass" for r in got):
        return "✅" if set(modes) == set(MODES) else "✅ " + "/".join(MODES[m] for m in modes)
    bad = [MODES[m] for m, r in zip(modes, got) if r["status"] != "pass"]
    return "❌ " + "/".join(bad)


def table(version: str | None = None) -> str:
    entries = [e for e in realiso.load() if not e.get("settings") and not e.get("unverifiable")]
    rows = {(r["id"], r["mode"], r["fs"]): r for r in realiso.latest_results(version=version)}
    out = ["| ISO | " + " | ".join(n for _, n in FILESYSTEMS) + " |",
           "|---|" + "---|" * len(FILESYSTEMS)]
    for e in entries:
        name = f"{e['name']}"
        out.append(f"| {name} | " + " | ".join(cell(e, fs, rows) for fs, _ in FILESYSTEMS) + " |")
    ver = version or realiso.beastboot_version()
    out += ["", LEGEND + ".", "",
            f"Generated by `scripts/iso_matrix.py` from the real-ISO boot checks of BeastBoot {ver} "
            "(`BB_REAL_ISO=1`, [tests/e2e/REAL_ISOS.md](tests/e2e/REAL_ISOS.md)); details per ISO in "
            "[docs/ISO_SUPPORT.md](docs/ISO_SUPPORT.md)."]
    return "\n".join(out) + "\n"


def splice(text: str, body: str) -> str:
    a, b = text.index(START) + len(START), text.index(END)
    return text[:a] + "\n" + body + text[b:]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--readme", action="store_true", help="update README.md between the markers")
    ap.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date")
    ap.add_argument("--version", help="BeastBoot version whose results to use (default: VERSION)")
    args = ap.parse_args(argv)
    body = table(args.version)
    if not (args.readme or args.check):
        sys.stdout.write(body)
        return 0
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = splice(text, body)
    if args.check:
        if new != text:
            print("iso_matrix: README.md's ISO table is out of date (scripts/iso_matrix.py --readme)", file=sys.stderr)
            return 1
        return 0
    readme.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
